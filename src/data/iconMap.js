export function resolveIconKey(value, fallback = 'help') {
  const safeFallback = Object.hasOwn(ICON_MAP, fallback)
    ? fallback
    : 'help'

  if (typeof value !== 'string') return safeFallback

  if (Object.hasOwn(ICON_MAP, value)) return value

  return LEGACY_EMOJI_TO_ICON_KEY[value] ?? safeFallback
}
